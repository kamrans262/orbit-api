import fs from 'node:fs';

const sos = fs.readFileSync('resources/js/admin-console/sos.js', 'utf8');
const index = fs.readFileSync('resources/js/admin-console/index.js', 'utf8');
const shell = fs.readFileSync('resources/js/admin-console/shell.js', 'utf8');
const sidebar = fs.readFileSync('resources/views/admin/partials/sidebar.blade.php', 'utf8');
const detail = fs.readFileSync('resources/views/admin/operations/sos/show.blade.php', 'utf8');
const contract = fs.readFileSync('resources/js/admin-console/sos-contract.js', 'utf8');
const ui = fs.readFileSync('resources/js/admin-console/ui.js', 'utf8');

const required = [
    [index, "from './sos.js'", 'M3 index import'],
    [index, "case 'sos-index'", 'SOS index boot'],
    [index, "case 'sos-show'", 'SOS detail boot'],
    [shell, "type.includes('sos')", 'global search SOS navigation'],
    [sidebar, "admin.console.operations.sos.index", 'real SOS sidebar route'],
    [sos, 'requestWithReauthentication', 'sensitive-action reauthentication flow'],
    [sos, "const fields = route?.fields ?? {}", 'route-proven operational closure field contract'],
    [sos, "await mutate(button, 'closure', closurePayload(values)", 'operational closure uses the generated exact request field contract'],
    [sos, 'applyActionPermissions', 'route-derived RBAC-aware action state'],
    [sos, 'readAdminSession', 'validated Foundation administrator permission source'],
    [sos, "adminApi('/api/admin/v1/auth/reauthenticate'", 'Foundation reauthentication endpoint'],
    [sos, 'clearSensitiveReveal', 'sensitive reveal clearing'],
    [sos, 'SENSITIVE_REVEAL_MS = 60000', '60-second sensitive reveal TTL'],
    [contract, 'Generated by setup/admin-ui-m3/generate-sos-contract.mjs', 'generated backend route contract'],
    [contract, 'permissions:', 'route-derived permission metadata'],
    [contract, '/api/admin/v1/sos/{sosId}/sensitive-access', 'real sensitive-access history route shape'],
    [contract, 'fields:', 'proven operational closure request fields'],
    [ui, 'data-dialog-cancel', 'cancel controls bypass required-field submission validation'],
    [ui, "button.addEventListener('click', () => dialog.close('cancel'))", 'explicit dialog cancellation'],
    [detail, 'reason-coded purpose', 'reason-coded sensitive access explanation'],
];

for (const [source, marker, label] of required) {
    if (!source.includes(marker)) throw new Error(`Missing ${label}: ${marker}`);
}


if (sos.includes('SOS_API.controls') || sos.includes('SOS_API.sensitive')) {
    throw new Error('SOS UI must not fall back from a required capability to a guessed generic backend route.');
}
if (contract.includes('/api/admin/v1/sos/{sosId}/controls')) {
    throw new Error('Packaged M3 contract must not contain the obsolete phantom /controls route.');
}

for (const unsafe of ['data-admin-auth-dialog', 'data-admin-auth-form']) {
    if (detail.includes(unsafe)) throw new Error(`M3 detail must not own authentication UI: ${unsafe}`);
}
for (const embeddedSensitive of ['latitude', 'longitude', 'recording_ref', 'ciphertext', 'private_key']) {
    if (detail.includes(embeddedSensitive)) throw new Error(`M3 Blade must not embed sensitive runtime data: ${embeddedSensitive}`);
}
if (sos.includes('JSON.stringify(incident)') || sos.includes('JSON.stringify(current)')) {
    throw new Error('SOS UI must whitelist operational fields instead of rendering arbitrary incident objects.');
}

console.log('Milestone 3 SOS UI static contract passed.');

if (/data-dialog-cancel[^>]*value="cancel"/.test(ui)) {
    throw new Error('Dialog cancellation controls must not be form submit buttons.');
}
if (!ui.includes('type="button" data-dialog-cancel')) {
    throw new Error('Dialog cancel/close controls must be explicit non-submit buttons.');
}
